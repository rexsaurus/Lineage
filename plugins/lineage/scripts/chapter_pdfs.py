#!/usr/bin/env python3
"""Every story as its own downloadable PDF, compressed like the book edition (Ghostscript /ebook, 150 dpi).

    python chapter_pdfs.py --project DIR            # every Typst story in data/chapters.csv
    python chapter_pdfs.py --project DIR cabin      # only stories whose file name contains "cabin"

Out: <chapters_dir>/<file stem>.pdf (settings.publish.chapters_dir, default output/chapters). r2_sync.py uploads
them under <prefix>/chapters/, where a published site's "Download" buttons find them.

The wrapper that turns one story into a document:
  - settings.publish.chapter_entry, when set: a Typst file the project supplies, compiled with
    --input chapter=<story file> --input title=<story title> --input updated=<date>;
  - otherwise a generated main.typ in .lineage/chapter-pdfs/ that imports Lineage's book template
    (#import "/book/template.typ": *, #show: book.with(...), #show: main-matter, #include "/<file>"), the same way
    the dashboard renders one story. The template is copied into the project's book/ when it is missing.
Without Ghostscript the uncompressed PDF is kept and a note is printed.
"""
import argparse
import csv
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _project import add_project_arg, enter_project  # noqa: E402
import _publish  # noqa: E402


def q(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


def main():
    ap = argparse.ArgumentParser(description="one compressed PDF per story")
    add_project_arg(ap)
    ap.add_argument("only", nargs="?", default="", help="only stories whose file name contains this text")
    a = ap.parse_args()
    root = enter_project(a.project)
    cfg = _publish.settings(root)
    if not shutil.which("typst"):
        sys.exit("typst is not installed: skipping chapter PDFs (brew install typst)")
    rows_p = Path("data/chapters.csv")
    if not rows_p.exists():
        print("no data/chapters.csv: no chapter PDFs to build")
        return
    rows = [r for r in csv.DictReader(open(rows_p, encoding="utf-8"))
            if (r.get("file") or "").endswith(".typ") and a.only in r["file"] and Path(r["file"]).is_file()]
    if not rows:
        print("no Typst stories match" + (f" '{a.only}'" if a.only else ""))
        return
    out_dir = Path(cfg["chapters_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    tpl, fonts = _publish.book_template()
    entry = cfg.get("chapter_entry") or ""
    if entry and not Path(entry).is_file():
        print(f"settings.publish.chapter_entry {entry} not found: using the generated wrapper")
        entry = ""
    if not entry:
        if not Path("book/template.typ").exists():
            if not tpl:
                sys.exit("no book/template.typ in the project and none in Lineage: cannot build chapter PDFs")
            Path("book").mkdir(exist_ok=True)
            shutil.copy2(tpl, "book/template.typ")
            print("copied Lineage's book template to book/template.typ")
    work = Path(".lineage/chapter-pdfs")
    work.mkdir(parents=True, exist_ok=True)
    trim = (_publish.lineage_json(root).get("settings") or {}).get("trim") or "7x10"
    updated = date.today().strftime("%-d %B %Y")
    built = 0
    for r in rows:
        f, title = r["file"], r.get("title") or Path(r["file"]).stem
        stem = Path(f).stem
        raw, out = work / f"{stem}.raw.pdf", out_dir / f"{stem}.pdf"
        cmd = ["typst", "compile", "--root", "."]
        if fonts:
            cmd += ["--font-path", str(fonts)]
        if entry:
            cmd += ["--input", f"chapter={f}", "--input", f"title={title}", "--input", f"updated={updated}", entry, str(raw)]
        else:
            main_typ = work / f"{stem}.typ"
            main_typ.write_text(
                "// GENERATED by chapter_pdfs.py: one story on its own. Not part of the book.\n"
                '#import "/book/template.typ": *\n'
                f'#show: book.with(title: "{q(cfg["title"])}", subtitle: "{q(cfg["subtitle"])}", trim: "{q(trim)}")\n'
                "#show: main-matter\n"
                f'#include "/{Path(f).as_posix().lstrip("/")}"\n', encoding="utf-8")
            cmd += [str(main_typ), str(raw)]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode:
            err = (res.stderr.strip().splitlines() or ["typst failed"])[0]
            print(f"  FAILED {f}: {err}")
            continue
        if _publish.gs_compress(raw, out):
            raw.unlink()
        else:
            shutil.move(str(raw), out)
            print("  (Ghostscript not found: kept the uncompressed PDF; brew install ghostscript)")
        built += 1
        print(f"  {out} ({out.stat().st_size // 1024} KB) — {title}")
    v = _publish.version(root)
    print(f"{built} chapter PDF(s) in {out_dir}/" + (f" for version {v}" if v else ""))


if __name__ == "__main__":
    main()
